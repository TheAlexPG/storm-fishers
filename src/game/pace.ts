// ─────────────────────────────────────────────────────────────
// Темп гри (налаштування; у кооп-кімнаті — як у господаря):
// −1 спокійний … +1 динамічний. Динамічний — клює частіше, але риба
// дешевша; спокійний — навпаки. Множник для очікування клювання й ціни
// той самий, тож за годину риболовлі заробіток приблизно рівний —
// різниця в ритмі й у тому, як швидко забивається трюм.
// ─────────────────────────────────────────────────────────────

let pace = 0;

export function setPace(v: number) {
  pace = Math.max(-1, Math.min(1, v));
}

export function getPace(): number {
  return pace;
}

/** множник очікування клювання й ціни риби: динамічний ×0,625, спокійний ×1,6 */
export function paceMul(): number {
  return Math.pow(1.6, -pace);
}
